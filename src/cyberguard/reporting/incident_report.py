from html import escape

from cyberguard.core.models import Incident


def incident_markdown(incident: Incident) -> str:
    sections = [
        f"# Incident Report: {incident.title}",
        f"**ID:** `{incident.id}`  \n**Severity:** {incident.severity.value.upper()}  \n**Status:** {incident.status.value}  \n**Confidence:** {incident.confidence:.0%}",
        f"## Executive summary\n{incident.summary}",
        f"## Likely root cause\n{incident.root_cause}",
        "## Evidence\n" + "\n".join(f"- {item.summary}" for item in incident.evidence),
        "## Analyst checks\n" + "\n".join(f"- {item}" for item in incident.analyst_checks),
        "## Safe remediation\n" + "\n".join(f"- {item}" for item in incident.remediation),
        "## Validation\n" + "\n".join(f"- {item}" for item in incident.validation),
        "## Limitations\n" + "\n".join(f"- {item}" for item in incident.limitations),
        "---\nGenerated by CyberGuard AI. Advisory output; analyst validation is required.",
    ]
    return "\n\n".join(sections) + "\n"


def incident_html(incident: Incident) -> str:
    def items(values: list[str]) -> str:
        return "".join(f"<li>{escape(value)}</li>" for value in values)
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>{escape(incident.title)}</title>
<style>body{{font:15px system-ui;max-width:900px;margin:48px auto;color:#182230;line-height:1.6}}h1,h2{{color:#0f2742}}.meta{{padding:16px;background:#eef5fa;border-left:4px solid #0891b2}}footer{{margin-top:40px;color:#64748b}}</style></head><body>
<h1>{escape(incident.title)}</h1><div class="meta"><b>Severity:</b> {incident.severity.value.upper()} &nbsp; <b>Confidence:</b> {incident.confidence:.0%}<br><b>ID:</b> {incident.id}</div>
<h2>Executive summary</h2><p>{escape(incident.summary)}</p><h2>Likely root cause</h2><p>{escape(incident.root_cause)}</p>
<h2>Evidence</h2><ul>{items([e.summary for e in incident.evidence])}</ul><h2>Analyst checks</h2><ul>{items(incident.analyst_checks)}</ul>
<h2>Safe remediation</h2><ul>{items(incident.remediation)}</ul><h2>Validation</h2><ul>{items(incident.validation)}</ul>
<h2>Limitations</h2><ul>{items(incident.limitations)}</ul><footer>Generated by CyberGuard AI · Advisory output · Analyst validation required</footer></body></html>"""
